-- ---------- child_profiles: phân biệt hồ sơ "con" và hồ sơ "người học bài bản" -------------------------------------
alter table public.child_profiles add column if not exists profile_type text not null default 'child';
alter table public.child_profiles drop constraint if exists child_profiles_profile_type_check;
alter table public.child_profiles add constraint child_profiles_profile_type_check
  check (profile_type in ('child', 'learner'));

-- ---------- cấp độ (mã CEFR: A1, A2, B1, B2, C1, C2) ----------------------------------------------------------------
create table if not exists public.bb_levels (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[ABC][12]$'),
  name_vi text not null,
  can_do text,                                    -- "có thể làm được gì" (can-do statement kiểu CEFR), free text
  sort_order int not null default 0,
  status text not null default 'draft' check (status in ('draft', 'approved')),
  created_at timestamptz not null default now()
);

-- ---------- chủ đề lớn trong 1 cấp -------------------------------------------------------------------------------
create table if not exists public.bb_units (
  id bigint generated by default as identity primary key,
  level_id bigint not null references public.bb_levels (id) on delete cascade,
  title_vi text not null,
  emoji text,
  description text,
  sort_order int not null default 0,
  status text not null default 'draft' check (status in ('draft', 'approved')),
  created_at timestamptz not null default now()
);
create index if not exists bb_units_level_idx on public.bb_units (level_id);

-- ---------- bài trong 1 chủ đề ------------------------------------------------------------------------------------
create table if not exists public.bb_lessons (
  id bigint generated by default as identity primary key,
  unit_id bigint not null references public.bb_units (id) on delete cascade,
  title_vi text not null,
  title_tr jsonb not null default '{}'::jsonb,     -- {"de":"...", "en":"..."} theo LANGUAGES của bản triển khai
  lesson_type text not null default 'core' check (lesson_type in ('core', 'review', 'reading', 'writing')),
  description text,
  sort_order int not null default 0,
  status text not null default 'draft' check (status in ('draft', 'approved')),
  created_at timestamptz not null default now()
);
create index if not exists bb_lessons_unit_idx on public.bb_lessons (unit_id);

-- ---------- chặng trong 1 bài (thứ tự tuần tự = sort_order) --------------------------------------------------------
create table if not exists public.bb_lesson_steps (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.bb_lessons (id) on delete cascade,
  step_type text not null check (step_type in
    ('dialogue', 'vocab', 'grammar', 'phonics', 'minigame', 'reading', 'writing')),
  config jsonb not null default '{}'::jsonb,       -- vd mini-game: {"kind":"flashcard_srs"}
  sort_order int not null default 0,
  status text not null default 'draft' check (status in ('draft', 'approved')),
  created_at timestamptz not null default now()
);
create index if not exists bb_lesson_steps_lesson_idx on public.bb_lesson_steps (lesson_id);

-- ---------- nội dung chặng Hội thoại ------------------------------------------------------------------------------
create table if not exists public.bb_dialogue_lines (
  id bigint generated by default as identity primary key,
  step_id bigint not null references public.bb_lesson_steps (id) on delete cascade,
  speaker text not null default 'A',               -- vai trong hội thoại (vd 'A'/'B'), khác quy ước dialogue trẻ em
  line_vi text not null,
  line_tr jsonb not null default '{}'::jsonb,
  audio_path text,
  sort_order int not null default 0
);
create index if not exists bb_dialogue_lines_step_idx on public.bb_dialogue_lines (step_id);

-- ---------- nội dung chặng Từ vựng --------------------------------------------------------------------------------
create table if not exists public.bb_vocab (
  id bigint generated by default as identity primary key,
  step_id bigint not null references public.bb_lesson_steps (id) on delete cascade,
  word_vi text not null,
  pos text,                                        -- loại từ: n, v, adj, adv…
  meaning jsonb not null default '{}'::jsonb,       -- {"de":"...", "en":"..."}
  image_path text,
  audio_path text,
  sort_order int not null default 0
);
create index if not exists bb_vocab_step_idx on public.bb_vocab (step_id);

-- ---------- nội dung chặng Ngữ pháp -------------------------------------------------------------------------------
create table if not exists public.bb_grammar (
  id bigint generated by default as identity primary key,
  step_id bigint not null references public.bb_lesson_steps (id) on delete cascade,
  formula text not null,                           -- "công thức hình họa", vd "Chào + đại từ"
  formula_tr jsonb not null default '{}'::jsonb,
  examples jsonb not null default '[]'::jsonb,      -- [{"vi":"...", "tr":{"de":"..."}}]
  sort_order int not null default 0
);
create index if not exists bb_grammar_step_idx on public.bb_grammar (step_id);

-- ---------- nội dung chặng Ngữ âm ---------------------------------------------------------------------------------
create table if not exists public.bb_phonics_pairs (
  id bigint generated by default as identity primary key,
  step_id bigint not null references public.bb_lesson_steps (id) on delete cascade,
  sound_a text not null,
  sound_b text not null,
  examples jsonb not null default '[]'::jsonb,      -- vd cặp từ minh hoạ dễ nhầm
  audio_a_path text,
  audio_b_path text,
  sort_order int not null default 0
);
create index if not exists bb_phonics_pairs_step_idx on public.bb_phonics_pairs (step_id);

-- ---------- nội dung chặng Đọc hiểu -------------------------------------------------------------------------------
create table if not exists public.bb_reading_passages (
  id bigint generated by default as identity primary key,
  step_id bigint not null references public.bb_lesson_steps (id) on delete cascade,
  passage_vi text not null,
  passage_tr jsonb not null default '{}'::jsonb,
  audio_path text
);
create index if not exists bb_reading_passages_step_idx on public.bb_reading_passages (step_id);

create table if not exists public.bb_reading_questions (
  id bigint generated by default as identity primary key,
  passage_id bigint not null references public.bb_reading_passages (id) on delete cascade,
  question_vi text not null,
  choices jsonb not null default '[]'::jsonb,
  answer int not null check (answer >= 1),          -- đếm từ 1, cùng quy ước content_items.extra Cấp 4 (app trẻ em)
  sort_order int not null default 0
);
create index if not exists bb_reading_questions_passage_idx on public.bb_reading_questions (passage_id);

-- ---------- nội dung chặng Luyện viết -----------------------------------------------------------------------------
create table if not exists public.bb_writing_tasks (
  id bigint generated by default as identity primary key,
  step_id bigint not null references public.bb_lesson_steps (id) on delete cascade,
  task_type text not null check (task_type in ('fill', 'order', 'write')),
  prompt_vi text not null,
  prompt_tr jsonb not null default '{}'::jsonb,
  -- hình dạng tuỳ task_type: fill {"sentence":"...","answer":"..."} · order {"words":[...]} · write {"min_words":20,"sample":"..."}
  content jsonb not null default '{}'::jsonb,
  sort_order int not null default 0
);
create index if not exists bb_writing_tasks_step_idx on public.bb_writing_tasks (step_id);

