-- RLS — cùng luật với nội dung trẻ em: admin xem/sửa hết; người dùng chỉ đọc mục ĐÃ DUYỆT khi còn hạn (has_access()).
-- ============================================================================

-- Bảng có status riêng (bb_levels/bb_units/bb_lessons/bb_lesson_steps): duyệt/nháp giống units/lessons/content_items.
do $$
declare t text;
begin
  foreach t in array array['bb_levels', 'bb_units', 'bb_lessons', 'bb_lesson_steps'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_read', t);
    execute format(
      'create policy %I on public.%I for select to authenticated using (public.is_admin() or (status = ''approved'' and public.has_access()))',
      t || '_read', t);
    execute format('drop policy if exists %I on public.%I', t || '_admin_write', t);
    execute format(
      'create policy %I on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())',
      t || '_admin_write', t);
  end loop;
end $$;

-- Nội dung theo chặng (không có status riêng): đọc được khi chặng CHA đã duyệt + còn hạn; ghi chỉ admin.
do $$
declare t text;
begin
  foreach t in array array['bb_dialogue_lines', 'bb_vocab', 'bb_grammar', 'bb_phonics_pairs',
                            'bb_reading_passages', 'bb_writing_tasks'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_read', t);
    execute format(
      'create policy %I on public.%I for select to authenticated using (public.is_admin() or (public.has_access() and exists (select 1 from public.bb_lesson_steps s where s.id = step_id and s.status = ''approved'')))',
      t || '_read', t);
    execute format('drop policy if exists %I on public.%I', t || '_admin_write', t);
    execute format(
      'create policy %I on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())',
      t || '_admin_write', t);
  end loop;
end $$;

-- Câu hỏi đọc hiểu: đi qua bảng đoạn văn để tới chặng (không có step_id trực tiếp).
alter table public.bb_reading_questions enable row level security;
drop policy if exists bb_reading_questions_read on public.bb_reading_questions;
create policy bb_reading_questions_read on public.bb_reading_questions for select to authenticated
  using (public.is_admin() or (public.has_access() and exists (
    select 1 from public.bb_reading_passages p join public.bb_lesson_steps s on s.id = p.step_id
     where p.id = passage_id and s.status = 'approved')));
drop policy if exists bb_reading_questions_admin_write on public.bb_reading_questions;
create policy bb_reading_questions_admin_write on public.bb_reading_questions for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
